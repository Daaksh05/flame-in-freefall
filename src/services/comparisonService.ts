import { Experiment, ComparisonDiff } from "@/types";
import { fetchFromBackend } from "./apiClient";
import { BENCHMARK_EXPERIMENTS } from "@/data/nasaBenchmarkData";

export interface MultiExperimentComparison {
  experiments: Experiment[];
  metrics: {
    metric: string;
    label: string;
    unit: string;
    values: (number | string | null)[];
    riskSummary?: string;
  }[];
  aiSynthesis?: string;
}

/**
 * Compare 2 or 3 microgravity combustion experiments side-by-side
 * Corresponds to FastAPI: GET /api/v1/experiments/compare?exp_ids=id1,id2,id3
 */
export async function compareExperiments(
  experimentIds: string[]
): Promise<MultiExperimentComparison> {
  const idsParam = experimentIds.join(",");

  try {
    return await fetchFromBackend<MultiExperimentComparison>("/api/v1/experiments/compare", {
      method: "GET",
      params: { exp_ids: idsParam },
    });
  } catch {
    // Generate comparison from local benchmark records
    const selected = experimentIds
      .map((id) => BENCHMARK_EXPERIMENTS.find((e) => e.id === id))
      .filter((e): e is Experiment => Boolean(e));

    const metrics = [
      {
        metric: "material",
        label: "Combustion Material",
        unit: "",
        values: selected.map((e) => e.material),
      },
      {
        metric: "platform",
        label: "Facility / Gravity Level",
        unit: "",
        values: selected.map((e) => e.platform.replace("_", " ")),
      },
      {
        metric: "oxygen_concentration",
        label: "Oxygen Concentration",
        unit: "% O₂",
        values: selected.map((e) => e.oxygen_concentration),
        riskSummary: "Elevated O₂ (>21%) exponentially lowers ignition energy and increases flame temperature.",
      },
      {
        metric: "flow_velocity",
        label: "Forced Flow Velocity",
        unit: "cm/s",
        values: selected.map((e) => (e.flow_velocity_cm_s === 0 ? "Quiescent (0.0)" : e.flow_velocity_cm_s)),
        riskSummary: "Weak convective flow (2-10 cm/s) prevents thermal starvation while avoiding blowoff.",
      },
      {
        metric: "chamber_pressure",
        label: "Chamber Ambient Pressure",
        unit: "kPa",
        values: selected.map((e) => e.ambient_pressure_kpa),
      },
      {
        metric: "flame_spread_rate",
        label: "Flame Spread Rate",
        unit: "mm/s",
        values: selected.map((e) => (e.flame_spread_rate_mm_s !== null ? e.flame_spread_rate_mm_s : "N/A (Droplet/Quenched)")),
        riskSummary: "Higher spread rates indicate accelerated flame front propagation across the solid substrate.",
      },
      {
        metric: "quenching_distance",
        label: "Quenching Distance",
        unit: "mm",
        values: selected.map((e) => (e.quenching_distance_mm !== null ? e.quenching_distance_mm : "N/A")),
        riskSummary: "Smaller quenching distance means flame can pass through tighter mesh screens or gaps.",
      },
      {
        metric: "burn_duration",
        label: "Total Burn Duration",
        unit: "s",
        values: selected.map((e) => (e.burn_duration_s !== null ? e.burn_duration_s : "N/A")),
      },
      {
        metric: "extinction_mode",
        label: "Extinction Mechanism",
        unit: "",
        values: selected.map((e) => e.extinction_mode),
        riskSummary: "Radiative extinction occurs when soot/gas radiation outpaces heat generated by reaction zone.",
      },
    ];

    const aiSynthesis = selected.length >= 2
      ? `Comparative analysis between ${selected.map((s) => s.test_run).join(" and ")} demonstrates that microgravity flammability is primarily governed by the balance between forced convective mass transfer and radiative soot cooling. Under forced ventilation (${selected[0].flow_velocity_cm_s} cm/s vs ${selected[1].flow_velocity_cm_s} cm/s), the flame envelope transitions from spherical diffuse radiation to an elongated parabolic boundary.`
      : "Select at least two experiments to view synthesis.";

    return {
      experiments: selected,
      metrics,
      aiSynthesis,
    };
  }
}
